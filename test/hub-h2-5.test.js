async function setup(t) {
  const database = await openDatabase({ filename: join(await temporaryDirectory(t), 'presence.sqlite') });
  t.after(() => database.close());
  const identity = createIdentityStore(database, { bootId: 'boot' });
  const rooms = createRoomStore(database, { identity });
  const changes = new EventEmitter();
  const events = createEventStore(database, { identity, rooms, onChange: roomId => changes.emit('room', roomId) });
  const delivery = createDeliveryStore(database, { identity, rooms, events });
  const deliveryService = createDeliveryService({ delivery, rooms, identity, changes });
  t.after(() => deliveryService.close());
  let time = Date.parse('2026-09-27T00:00:00.000Z');
  const options = { identity, rooms, events, deliveryService, now: () => time, ttlMs: 1000 };
  const presence = createPresenceService(options);
  t.after(() => presence.close());
  const sessions = createLocalSession({ identity, presence, changes });
  const browser = sessions.browserSession();
  const human = identity.authenticate({ cookie: browser.token });
  const room = rooms.create(human, { request_id: 'room', name: 'Room' });
  const input = { mode: 'create', request_id: 'enroll', resume_token: 's'.repeat(32), name: 'Agent' };
  const agent = sessions.agentSession(input);
  const context = identity.authenticate({ bearer: agent.token });
  rooms.join(context, room.id, { request_id: 'join' });
  const status = () => Outputs.participants.parse(presence.list(human, room.id)).participants.find(item => item.participant.id === agent.participant.id);
  return { database, identity, rooms, events, delivery, deliveryService, presence, sessions, browser, human, room, input, agent, context, options, status, advance: ms => { time += ms; } };
}

test('presence timestamps expire independently and ordinary touches do not refresh reported activity', async t => {
  const s = await setup(t);
  assert.equal(s.status().connection, 'connected');
  assert.equal(s.status().delivery, 'idle');
  assert.equal(s.status().activity, null);
  s.sessions.heartbeat(s.context, { activity: 'Reviewing' });
  const reported = s.status().activity.reported_at;
  s.advance(500);
  s.presence.touch(s.context);
  assert.equal(s.status().activity.reported_at, reported);
  assert.equal(s.status().last_seen_at, '2026-09-27T00:00:00.500Z');
  s.advance(500);
  assert.equal(s.status().connection, 'connected');
  assert.equal(s.status().activity, null);
  s.advance(500);
  assert.equal(s.status().connection, 'disconnected');
  assert.equal(s.status().last_seen_at, null);
  assert.equal(s.status().activity, null);
  s.presence.touch(s.context);
  assert.equal(s.status().connection, 'connected');
  assert.equal(s.status().activity, null);
  assert.throws(() => s.presence.touch(s.context, { activity: 'x'.repeat(501) }), { code: 'VALIDATION_ERROR' });
});

test('pending raw counts, receiving and pause remain separate from connection and reported activity', async t => {
  const s = await setup(t);
  s.presence.touch(s.context, { activity: 'Thinking' });
  const controller = new AbortController();
  const wait = s.deliveryService.receive(s.context, s.room.id, {}, { signal: controller.signal });
  assert.equal(s.status().delivery, 'receiving');
  s.advance(1000);
  assert.equal(s.status().connection, 'disconnected');
  assert.equal(s.status().delivery, 'receiving');
  assert.equal(s.status().activity, null);
  s.events.post(s.context, s.room.id, { request_id: 'self', text: 'self' });
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(s.status().delivery, 'receiving');
  assert.equal(s.status().pending_count, 0);
  const peer = s.events.post(s.human, s.room.id, { request_id: 'peer', text: 'peer' });
  const batch = (await wait).batch;
  assert.equal(s.status().delivery, 'idle');
  assert.equal(s.status().pending_count, 1);
  assert.deepEqual(batch.events, [peer]);
  const human = s.presence.list(s.human, s.room.id).participants.find(item => item.participant.kind === 'human');
  assert.equal(human.pending_count, 0);
  s.delivery.ack(s.context, s.room.id, { request_id: 'ack', batch_id: batch.id, membership_epoch: batch.membership_epoch });
  assert.equal(s.status().pending_count, 0);
  s.database.db.prepare('UPDATE memberships SET paused=1 WHERE room_id=? AND participant_id=?').run(s.room.id, s.agent.participant.id);
  s.presence.touch(s.context, { activity: 'Still working' });
  assert.equal(s.status().delivery, 'paused');
  assert.equal(s.status().connection, 'connected');
  assert.equal(s.status().activity.text, 'Still working');
});

test('generation replacement and durable disconnect invalidate cached observations; late disconnect preserves a newer one', async t => {
  const s = await setup(t);
  s.presence.touch(s.context, { activity: 'Old task' });
  const resumed = s.identity.agentSession({ ...s.input, mode: 'resume', request_id: 'resume' });
  assert.equal(s.status().connection, 'disconnected');
  assert.equal(s.status().last_seen_at, null);
  assert.equal(s.status().activity, null);
  assert.throws(() => s.presence.touch(s.context), { code: 'SESSION_REPLACED' });
  const current = s.identity.authenticate({ bearer: resumed.token });
  s.presence.touch(current);
  s.presence.disconnect(s.context);
  assert.equal(s.status().connection, 'connected');
  assert.equal(s.status().activity, null);
  s.identity.disconnect(current);
  assert.equal(s.status().connection, 'disconnected');
  const again = s.sessions.agentSession({ ...s.input, mode: 'resume', request_id: 'again' });
  const last = s.identity.authenticate({ bearer: again.token });
  assert.equal(s.status().connection, 'connected');
  s.sessions.disconnect(last);
  assert.equal(s.status().connection, 'disconnected');
});

test('fresh instances start empty, membership checks protect snapshots and close is idempotent', async t => {
  const s = await setup(t);
  const restarted = createPresenceService(s.options);
  const values = restarted.list(s.human, s.room.id).participants;
  assert.ok(values.every(item => item.connection === 'disconnected' && item.last_seen_at === null && item.activity === null));
  const other = s.rooms.create(s.human, { request_id: 'other', name: 'Other' });
  assert.throws(() => s.presence.list(s.context, other.id), { code: 'FORBIDDEN' });
  const member = s.rooms.requireMembership(s.context, s.room.id);
  s.rooms.leave(s.context, s.room.id, { request_id: 'leave', membership_epoch: member.epoch });
  assert.equal(s.presence.list(s.human, s.room.id).participants.length, 1);
  assert.throws(() => s.presence.list(s.context, s.room.id), { code: 'FORBIDDEN' });
  s.presence.close();
  s.presence.close();
  s.presence.touch(s.human);
  assert.equal(s.presence.list(s.human, s.room.id).participants[0].connection, 'disconnected');
  restarted.close();
});

test('participants route matches only exact GET and authenticates before room-scoped output', async t => {
  const s = await setup(t);
  const route = createPresenceRoutes({ sessions: s.sessions, presence: s.presence });
  const request = { headers: { authorization: `Bearer ${s.agent.token}` }, rawHeaders: [] };
  const path = `/api/v1/rooms/${s.room.id}/participants`;
  const result = route({ request, method: 'GET', path });
  assert.equal(result.schema, 'participants');
  Outputs.participants.parse(result.data);
  assert.equal(result.data.participants.length, 2);
  assert.equal(route({ request, method: 'POST', path }), undefined);
  assert.equal(route({ request, method: 'GET', path: `${path}/extra` }), undefined);
  assert.throws(() => route({ request: { headers: {}, rawHeaders: [] }, method: 'GET', path }), { code: 'UNAUTHENTICATED' });
  assert.throws(() => route({ request, method: 'GET', path: '/api/v1/rooms/%xx/participants' }), { code: 'VALIDATION_ERROR' });
  const json = JSON.stringify(result.data);
  assert.ok(!json.includes(s.agent.token));
  assert.ok(!json.includes(s.input.resume_token));
});
